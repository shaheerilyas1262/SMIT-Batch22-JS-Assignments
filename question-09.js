// Question 9: Age Calculator
// Concept: Current year and subtraction

// We ask the user for their birth year and subtract it from the current year.




// Ask for birth year
var birthYear = Number(prompt("Enter your birth year:"));

// Get current year
var currentYear = 2026;

// Calculate approximate age
var age = currentYear - birthYear;

// Display age
console.log("Your approximate age is " + age + " years.");
